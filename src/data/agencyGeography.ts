export const getAgencyGeography = (code: any, name?: string): GeographyInfo => {
  const normCode = String(code || "").trim().replace(/^0+(?!$)/, "");
  if (AGENCY_GEOGRAPHY[normCode]) {
    return AGENCY_GEOGRAPHY[normCode];
  }

  const normName = String(name || "").toLowerCase().trim();
  
  if (normName.includes("barcelone") || normName.includes("bnet") || normName.includes("jaures") || normName.includes("jaurès") || normName.includes("lafayette") || normName.includes("marsa")) {
    return { delegation: "Tunis Centre", gouvernorat: "Tunis" };
  }
  if (normName.includes("bizerte") || normName.includes("ariana") || normName.includes("bardo") || normName.includes("lac") || normName.includes("manar") || normName.includes("mnihla") || normName.includes("enasr") || normName.includes("menzah") || normName.includes("kram") || normName.includes("soukra")) {
    return { delegation: "Tunis Nord", gouvernorat: "Bizerte" };
  }
  if (normName.includes("ben arous") || normName.includes("mourouj") || normName.includes("hammam lif") || normName.includes("fouchana") || normName.includes("rades") || normName.includes("radès") || normName.includes("megrine") || normName.includes("mégrine") || normName.includes("ezzahra")) {
    return { delegation: "Tunis Sud", gouvernorat: "Ben Arous" };
  }
  if (normName.includes("sousse") || normName.includes("monastir") || normName.includes("kairouan") || normName.includes("moknine") || normName.includes("jemmel") || normName.includes("msaken") || normName.includes("m'saken")) {
    return { delegation: "Sahel", gouvernorat: "Sousse" };
  }
  if (normName.includes("sfax") || normName.includes("mahdia") || normName.includes("gabes") || normName.includes("gabès") || normName.includes("chebba") || normName.includes("boumerdes") || normName.includes("boumerdès") || normName.includes("el-jem") || normName.includes("hamma")) {
    return { delegation: "Sfax", gouvernorat: "Sfax" };
  }
  if (normName.includes("nabeul") || normName.includes("kelibia") || normName.includes("kélibia") || normName.includes("hammamet") || normName.includes("soliman") || normName.includes("zaghouan")) {
    return { delegation: "Cap Bon", gouvernorat: "Nabeul" };
  }
  if (normName.includes("beja") || normName.includes("béja") || normName.includes("kef") || normName.includes("siliana") || normName.includes("jendouba") || normName.includes("testour") || normName.includes("mjez") || normName.includes("kasserine") || normName.includes("feriana") || normName.includes("ghardimaou") || normName.includes("bousselem")) {
    return { delegation: "Nord ouest", gouvernorat: "Béja" };
  }
  if (normName.includes("djerba") || normName.includes("gafsa") || normName.includes("zarzis") || normName.includes("tataouine") || normName.includes("kebili") || normName.includes("kébili") || normName.includes("tozeur") || normName.includes("medenine") || normName.includes("médenine") || normName.includes("gerdane")) {
    return { delegation: "Sud", gouvernorat: "Médenine" };
  }

  return { delegation: "Tunis Centre", gouvernorat: "Tunis" };
};

